def login(self):
    """
        Logs into the Eamena Arches instance.
        Requests the index page in order to generate a session and csrf token, which are
        saved in this object's variables.

        :returns response: The request's response object.
    """

    response = {
        "status": 0,
        "session": None
    }

    session = requests.Session()
    # Request the homepage to begin a session.
    session.get(endpoints["index"])

    # Set the Object's internal csrf token for later use
    csrf_token = session.cookies.get('csrftoken')

    # Get the pregenerated headers
    headers = get_headers()

    # Set the data payload to be sent, including csrf token, username and password
    login_data = get_login_data()

    login_request = requests.post(endpoints["log_in"], data=login_data, headers=headers)

    response["status"] = login_request.status_code
    request_cookies = login_request.request.headers["cookie"]

    # Determine the csrf and session (named eamena) token
    eamena_token = request_cookies.split("eamena=")[1]
    csrf_token = request_cookies.split("csrftoken=")[1].split(";")[0]

    self.eamena_token = eamena_token
    self.csrf_token = csrf_token
    # TODO - Should really be just returning some kind of error message instead!
    return response


def get_parent_id( nodegroup_id, resource_id):
    """
    Makes a request to the Arches instance to determine the resource instance_id value of a given resource object.
    This must be requested
    """
    base_parent_payload = {
        "tileid": "",
        "data": {},
        "nodegroup_id": nodegroup_id,
        "parenttile_id": None,
        "resourceinstance_id": resource_id,
        "sortorder": 0,
        "tiles": {}
    }

    parent_payload = {
        'data': json.dumps(base_parent_payload, ensure_ascii=False)
    }

    parent_request = requests.post(endpoints["tile"], headers=get_headers(content_type="json"), data=parent_payload)

    if parent_request.status_code == 200:
        parent_response = json.loads(parent_request.content)
        return parent_response["tileid"]
    else:
        return None


def get_resource_descriptors(resource_id):
    """
    Retrieves the resource descriptors valuse for a given resource.
    contains: display description, display name, geometries, graph name, graphi_id, map_popup, permissions, userid

    :param resource_id: str - The resource UUID value
    :returns: Dictionary containing relevant resource descriptor values, status and result message
    """

    result_dict = {
        "status": False,
        "message": None,
        "content": ""
    }

    response = requests.get(endpoints["get_descriptors"] + resource_id)

    if response.status_code == 200:
        result_dict["content"] = json.loads(response.content)
        result_dict["message"] = "success"
        result_dict["status"] = True
    else:
        result_dict["message"] = response.reason
        result_dict["status"] = False

    return result_dict


